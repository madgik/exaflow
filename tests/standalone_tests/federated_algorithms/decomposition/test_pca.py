class TestFederatedPCA(FederatedAlgorithmTest):
    def compute_centralized_result(self, X, y, **kwargs):
        sk_model = Pipeline(
            [
                ("scaler", StandardScaler(with_mean=True, with_std=True)),
                ("pca", PCA(svd_solver="full")),
            ]
        )
        sk_model.fit(X)
        return {
            "model": sk_model,
            "n_samples": X.shape[0],
        }

    def compute_federated_result(self, X, y, *, agg_client, **kwargs):
        model = FederatedPCA(agg_client=agg_client)
        model.fit(X)
        return model

    def compare(self, federated_output, centralized_output, **kwargs):
        model = centralized_output["model"]
        n_samples = centralized_output["n_samples"]
        assert federated_output.n_samples_seen_ == n_samples
        assert np.allclose(
            federated_output.explained_variance_,
            # sklearn StandardScaler uses population variance (ddof=0); our PCA uses sample variance (ddof=1)
            model.named_steps["pca"].explained_variance_
            * (
                (federated_output.n_samples_seen_ - 1)
                / federated_output.n_samples_seen_
            ),
            atol=1e-8,
        )

        fed_components = np.asarray(federated_output.components_, dtype=float)
        cen_components = np.asarray(model.named_steps["pca"].components_, dtype=float)
        for i in range(fed_components.shape[0]):
            ai = fed_components[i] / np.linalg.norm(fed_components[i])
            bi = cen_components[i] / np.linalg.norm(cen_components[i])
            assert np.isclose(abs(np.dot(ai, bi)), 1.0, atol=1e-8)

        identity = np.eye(federated_output.components_.shape[0], dtype=float)
        assert np.allclose(
            federated_output.components_ @ federated_output.components_.T,
            identity,
            atol=1e-8,
        )

    @pytest.mark.parametrize("X", TEST_CASES)
    def test_federated_algorithm_with_one_worker(self, X):
        self.run_comparison(X=X, y=np.zeros((X.shape[0],), dtype=float), n_workers=1)

    @pytest.mark.parametrize("X", TEST_CASES)
    def test_federated_algorithm_with_multiple_workers(self, X):
        self.run_comparison(X=X, y=np.zeros((X.shape[0],), dtype=float), n_workers=3)
