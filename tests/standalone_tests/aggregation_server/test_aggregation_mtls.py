def test_unregister_after_in_progress_submission_is_rejected(mtls):
    endpoint = mtls["endpoint"]
    controller = ControllerAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("controller")
    )
    w1 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w1")
    )
    w2 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w2")
    )
    try:
        _configure(controller, 2, ["w1", "w2"])
        ctx = mtls["servicer"].aggregation_contexts["ctx"]
        with ThreadPoolExecutor(max_workers=2) as pool:
            first = pool.submit(
                w1._aggregate_batch_request, [(AggregationType.SUM, [1.0])], step=1
            )
            deadline = time.monotonic() + 5
            while time.monotonic() < deadline:
                if 1 in ctx.steps and "w1" in ctx.steps[1].submitted_workers:
                    break
                time.sleep(0.01)

            with pytest.raises(grpc.RpcError) as exc:
                w1.unregister()
            assert exc.value.code() == grpc.StatusCode.FAILED_PRECONDITION
            assert ctx.active_worker_ids == {"w1", "w2"}
            assert ctx.error is None

            second = pool.submit(
                w2._aggregate_batch_request, [(AggregationType.SUM, [2.0])], step=1
            )
            assert first.result(timeout=5)[0].tolist() == [3.0]
            assert second.result(timeout=5)[0].tolist() == [3.0]
    finally:
        controller.close()
        w1.close()
        w2.close()


def test_replayed_step_after_completion_and_malformed_duplicate_do_not_fail_context(
    mtls,
):
    endpoint = mtls["endpoint"]
    controller = ControllerAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("controller")
    )
    w1 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w1")
    )
    w2 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w2")
    )
    try:
        _configure(controller, 2, ["w1", "w2"])
        with ThreadPoolExecutor(max_workers=2) as pool:
            f1 = pool.submit(
                w1._aggregate_batch_request, [(AggregationType.SUM, [1.0])], step=1
            )
            f2 = pool.submit(
                w2._aggregate_batch_request, [(AggregationType.SUM, [2.0])], step=1
            )
            assert f1.result(timeout=5)[0].tolist() == [3.0]
            assert f2.result(timeout=5)[0].tolist() == [3.0]

        # Replaying completed step 1 (even with malformed payload) returns
        # ALREADY_EXISTS and leaves the context healthy for step 2.
        malformed_replay = pb2.AggregateRequest(
            request_id="rid",
            context_id="ctx",
            step=1,
            operations=[pb2.Operation(aggregation_type="AVG", tensor=b"bad")],
        )
        with pytest.raises(grpc.RpcError) as exc:
            _call(endpoint, mtls["client_tls"]("w1"), "Aggregate", malformed_replay)
        assert exc.value.code() == grpc.StatusCode.ALREADY_EXISTS
        assert mtls["servicer"].aggregation_contexts["ctx"].error is None

        with ThreadPoolExecutor(max_workers=2) as pool:
            f1 = pool.submit(
                w1._aggregate_batch_request, [(AggregationType.SUM, [10.0])], step=2
            )
            f2 = pool.submit(
                w2._aggregate_batch_request, [(AggregationType.SUM, [20.0])], step=2
            )
            assert f1.result(timeout=5)[0].tolist() == [30.0]
            assert f2.result(timeout=5)[0].tolist() == [30.0]
    finally:
        controller.close()
        w1.close()
        w2.close()


def test_create_servers_rejects_invalid_tls_and_port_configs(monkeypatch, certs):
    from dataclasses import replace

    # TLS enabled with require_client_auth=False must fail closed.
    monkeypatch.setattr(
        agg_config,
        "tls",
        replace(_server_tls(certs), require_client_auth=False),
    )
    monkeypatch.setattr(agg_config, "federation", "dementia")
    monkeypatch.setattr(agg_config, "health_port", 0)
    with pytest.raises(ValueError, match="require_client_auth"):
        server_module._create_servers()

    # Blank federation under mTLS must fail closed.
    monkeypatch.setattr(agg_config, "tls", _server_tls(certs))
    monkeypatch.setattr(agg_config, "federation", "")
    with pytest.raises(ValueError, match="FEDERATION"):
        server_module._create_servers()

    # health_port colliding with main port must fail.
    monkeypatch.setattr(agg_config, "federation", "dementia")
    monkeypatch.setattr(agg_config, "port", 50051)
    monkeypatch.setattr(agg_config, "health_port", 50051)
    with pytest.raises(ValueError, match="health_port"):
        server_module._create_servers()


