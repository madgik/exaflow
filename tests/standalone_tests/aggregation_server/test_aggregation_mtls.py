def _openssl(folder: Path, *args) -> None:
    if shutil.which("openssl") is None:
        pytest.skip("openssl binary is required for mTLS certificate tests")
    result = subprocess.run(
        ["openssl", *[str(arg) for arg in args]],
        cwd=folder,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, f"openssl failed: {result.stderr}"


def _make_ca(folder: Path, name: str) -> tuple[Path, Path]:
    key = folder / f"{name}.key"
    cert = folder / f"{name}.crt"
    _openssl(
        folder,
        "req",
        "-x509",
        "-newkey",
        "ec",
        "-pkeyopt",
        "ec_paramgen_curve:prime256v1",
        "-nodes",
        "-keyout",
        key.name,
        "-out",
        cert.name,
        "-days",
        "2",
        "-subj",
        f"/CN={name}",
        "-addext",
        "basicConstraints=critical,CA:TRUE",
        "-addext",
        "keyUsage=critical,keyCertSign,cRLSign",
    )
    return key, cert


def _issue_leaf(
    folder: Path,
    ca_key: Path,
    ca_cert: Path,
    name: str,
    san: str,
) -> tuple[Path, Path]:
    key = folder / f"{name}.key"
    csr = folder / f"{name}.csr"
    cert = folder / f"{name}.crt"
    ext = folder / f"{name}.ext"
    _openssl(
        folder,
        "req",
        "-newkey",
        "ec",
        "-pkeyopt",
        "ec_paramgen_curve:prime256v1",
        "-nodes",
        "-keyout",
        key.name,
        "-out",
        csr.name,
        "-subj",
        f"/CN={name}",
    )
    ext.write_text(
        "basicConstraints=CA:FALSE\n"
        "extendedKeyUsage=clientAuth,serverAuth\n"
        f"subjectAltName={san}\n"
    )
    _openssl(
        folder,
        "x509",
        "-req",
        "-in",
        csr.name,
        "-CA",
        ca_cert.name,
        "-CAkey",
        ca_key.name,
        "-CAcreateserial",
        "-out",
        cert.name,
        "-days",
        "2",
        "-extfile",
        ext.name,
    )
    return key, cert


