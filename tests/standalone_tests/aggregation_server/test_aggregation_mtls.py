class _AuthContext:
    def __init__(self, auth):
        self._auth = auth

    def auth_context(self):
        return self._auth


def test_extract_peer_identity_controller_and_worker():
    controller = extract_peer_identity(
        _AuthContext(
            {
                "transport_security_type": [b"ssl"],
                "peer_uri": [b"exaflow://dementia/controller"],
            }
        )
    )
    assert controller == PeerIdentity(
        "controller", "dementia", None, "exaflow://dementia/controller"
    )

    worker = extract_peer_identity(
        _AuthContext(
            {
                "transport_security_type": [b"ssl"],
                "peer_uri": [b"exaflow://dementia/worker/w1"],
            }
        ),
        expected_federation="dementia",
    )
    assert worker == PeerIdentity(
        "worker", "dementia", "w1", "exaflow://dementia/worker/w1"
    )


