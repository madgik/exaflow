def test_non_member_worker_cannot_poison_honest_aggregation(mtls):
    endpoint = mtls["endpoint"]
    controller = ControllerAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("controller")
    )
    w1 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w1")
    )
    w2 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w2")
    )
    w3 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w3")
    )
    try:
        _configure(controller, 2, ["w1", "w2"])
        with ThreadPoolExecutor(max_workers=2) as pool:
            f1 = pool.submit(w1.sum, [1.0])
            f2 = pool.submit(w2.sum, [2.0])
            ctx = mtls["servicer"].aggregation_contexts["ctx"]
            _wait_until(lambda: 1 in ctx.steps or ctx.last_completed_step >= 1)

            with pytest.raises(grpc.RpcError) as exc:
                w3._aggregate_batch_request([(AggregationType.SUM, [99.0])], step=1)
            assert exc.value.code() == grpc.StatusCode.PERMISSION_DENIED

            with pytest.raises(grpc.RpcError) as exc:
                w3.unregister()
            assert exc.value.code() == grpc.StatusCode.PERMISSION_DENIED

            assert f1.result(timeout=5).tolist() == [3.0]
            assert f2.result(timeout=5).tolist() == [3.0]

        assert ctx.error is None
        assert ctx.expected_workers == 2
    finally:
        controller.close()
        w1.close()
        w2.close()
        w3.close()


def test_duplicate_submission_is_rejected_without_double_counting(mtls):
    endpoint = mtls["endpoint"]
    controller = ControllerAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("controller")
    )
    w1 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w1")
    )
    w2 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w2")
    )
    try:
        _configure(controller, 2, ["w1", "w2"])
        ctx = mtls["servicer"].aggregation_contexts["ctx"]
        with ThreadPoolExecutor(max_workers=2) as pool:
            first = pool.submit(
                w1._aggregate_batch_request, [(AggregationType.SUM, [1.0])], step=1
            )
            _wait_until(
                lambda: 1 in ctx.steps and "w1" in ctx.steps[1].submitted_workers
            )

            with pytest.raises(grpc.RpcError) as exc:
                w1._aggregate_batch_request([(AggregationType.SUM, [100.0])], step=1)
            assert exc.value.code() == grpc.StatusCode.ALREADY_EXISTS

            second = pool.submit(
                w2._aggregate_batch_request, [(AggregationType.SUM, [2.0])], step=1
            )
            assert first.result(timeout=5)[0].tolist() == [3.0]
            assert second.result(timeout=5)[0].tolist() == [3.0]

        assert ctx.error is None
        assert 1 not in ctx.steps  # the step completed and was cleaned up
    finally:
        controller.close()
        w1.close()
        w2.close()


def test_unregister_to_one_attack_is_blocked(mtls):
    endpoint = mtls["endpoint"]
    controller = ControllerAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("controller")
    )
    w1 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w1")
    )
    w3 = Exareme3UDFAggregationClient(
        "rid", "ctx", aggregator_dns=endpoint, tls=mtls["client_tls"]("w3")
    )
    try:
        _configure(controller, 2, ["w1", "w2"])
        status, remaining = w1.unregister()
        assert status == pb2.Status.OK
        assert remaining == 1

        ctx = mtls["servicer"].aggregation_contexts["ctx"]
        assert ctx.active_worker_ids == {"w2"}
        assert ctx.expected_workers == 1

        with pytest.raises(grpc.RpcError) as exc:
            w1.unregister()
        assert exc.value.code() == grpc.StatusCode.PERMISSION_DENIED

        with pytest.raises(grpc.RpcError) as exc:
            w3.unregister()
        assert exc.value.code() == grpc.StatusCode.PERMISSION_DENIED

        assert ctx.expected_workers == 1
        assert ctx.active_worker_ids == {"w2"}
        assert ctx.error is None
    finally:
        controller.close()
        w1.close()
        w3.close()


def test_dedicated_health_port_exposes_only_health(monkeypatch, certs):
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        health_port = probe.getsockname()[1]

    server_tls = _server_tls(certs)
    monkeypatch.setattr(agg_config, "tls", server_tls)
    monkeypatch.setattr(agg_config, "federation", "dementia")
    monkeypatch.setattr(agg_config, "health_port", health_port)

    main_server, health_server = server_module._create_servers()
    main_server.add_secure_port("127.0.0.1:0", build_server_credentials(server_tls))
    health_server.add_insecure_port(f"127.0.0.1:{health_port}")
    main_server.start()
    health_server.start()
    try:
        with grpc.insecure_channel(f"127.0.0.1:{health_port}") as channel:
            response = health_pb2_grpc.HealthStub(channel).Check(
                health_pb2.HealthCheckRequest(service="Aggregation"), timeout=3
            )
            assert response.status == health_pb2.HealthCheckResponse.SERVING

            with pytest.raises(grpc.RpcError) as exc:
                AggregationServerStub(channel).Configure(
                    _request("Configure", num_of_workers=1, worker_ids=["w1"]),
                    timeout=3,
                )
            assert exc.value.code() == grpc.StatusCode.UNIMPLEMENTED
    finally:
        health_server.stop(0)
        main_server.stop(0)


