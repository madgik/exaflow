def _request(rpc: str, **fields):
    values = {"request_id": "rid", "context_id": "ctx"}
    values.update(fields)
    return getattr(pb2, f"{rpc}Request")(**values)


def _call(endpoint, tls, rpc, request, *, metadata=OWNER_METADATA, timeout=5):
    with grpc.secure_channel(
        endpoint,
        build_channel_credentials(tls),
        options=channel_options_with_tls(tls),
    ) as channel:
        return getattr(AggregationServerStub(channel), rpc)(
            request, timeout=timeout, metadata=metadata
        )


def _plaintext_call(endpoint, rpc, request, *, timeout=5):
    with grpc.insecure_channel(endpoint) as channel:
        return getattr(AggregationServerStub(channel), rpc)(request, timeout=timeout)


def _wait_until(predicate, timeout=5.0):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return
        time.sleep(0.01)
    raise AssertionError("condition was not met before the timeout")


def _configure(controller, num_workers, worker_ids):
    assert (
        controller.configure(num_workers=num_workers, worker_ids=worker_ids, timeout=10)
        == pb2.Status.OK
    )


