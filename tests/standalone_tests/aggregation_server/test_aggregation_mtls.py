def _server_tls(certs) -> GrpcTlsConfig:
    key, cert = certs["server"]
    return GrpcTlsConfig(
        enabled=True,
        ca_cert_path=str(certs["ca"]),
        cert_path=str(cert),
        key_path=str(key),
        require_client_auth=True,
    )


def _client_tls(certs, name: str, ca: Path | None = None) -> GrpcTlsConfig:
    key, cert = certs[name]
    return GrpcTlsConfig(
        enabled=True,
        ca_cert_path=str(ca or certs["ca"]),
        cert_path=str(cert),
        key_path=str(key),
    )


